class DriverEntity {
  final String firstName;
  final String lastName;
  final String vehicleType;
  final String vehicleNumber;
  final String email;
  final String phone;
  final String photo;

  const DriverEntity({
    required this.firstName,
    required this.lastName,
    required this.vehicleType,
    required this.vehicleNumber,
    required this.email,
    required this.phone,
    required this.photo,
  });
}
